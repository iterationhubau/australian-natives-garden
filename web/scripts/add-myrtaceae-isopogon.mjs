function plant(p) {
  return {
    pretreatment: p.pretreatment || 'None Required (cutting-grown / nursery stock common)',
    germination: p.germination || 'Cuttings preferred for cultivars. Species seed: sow on sandy native mix surface, keep lightly moist; smoke may help some banksias.',
    growth_rate: p.growth_rate || 'Moderate',
    conservation_status: p.conservation_status || (String(p.scientific_name).includes("'") ? 'Cultivar' : 'Least Concern'),
    conservation_locale: p.conservation_locale || (String(p.scientific_name).includes("'") ? 'Garden / nursery selection' : 'Australia'),
    conservation_description:
      p.conservation_description ||
      (String(p.scientific_name).includes("'")
        ? 'Garden cultivar / selection; not assessed as a wild conservation taxon.'
        : 'Secure in suitable native habitats; widely grown in Australian gardens.'),
    shade_tolerance: p.shade_tolerance || 'Full sun',
    water_requirement: p.water_requirement ?? 3,
    image_url: p.image_url || '',
    image_attribution: '',
    image_license: '',
    image_source: null,
    ...p,
  }
}

