const NEW_PLANTS = [...GREVILLEA, ...CORREA, ...WESTRINGIA, ...OTHER_POPULAR]

const existingNames = new Set(species.map((s) => s.scientific_name.toLowerCase()))
const added = []
let nextId = Math.max(0, ...species.map((s) => Number(s.legacy_id) || 0)) + 1
const byGenus = {}

for (const raw of NEW_PLANTS) {
  if (existingNames.has(raw.scientific_name.toLowerCase())) {
    console.log('Skip existing:', raw.scientific_name)
    continue
  }
  const image_source = String(raw.image_url || '').includes('wikimedia.org') ? 'library_cc' : 'web_link'
  const row = {
    legacy_id: String(nextId++),
    scientific_name: raw.scientific_name,
    common_name: raw.common_name,
    genus: raw.genus,
    pretreatment: raw.pretreatment,
    germination: raw.germination,
    growth_rate: raw.growth_rate,
    mature_height: raw.mature_height,
    mature_width: raw.mature_width,
    foliage: raw.foliage,
    flowers: raw.flowers,
    flowering_time: raw.flowering_time,
    soil_preference: raw.soil_preference,
    frost_tolerance: raw.frost_tolerance,
    drought_tolerance: raw.drought_tolerance,
    shade_tolerance: raw.shade_tolerance,
    water_requirement: raw.water_requirement,
    conservation_status: raw.conservation_status,
    conservation_locale: raw.conservation_locale,
    conservation_description: raw.conservation_description,
    image_url: raw.image_url || '',
    image_attribution: image_source === 'library_cc' ? 'Wikimedia Commons' : '',
    image_license: image_source === 'library_cc' ? 'See source page' : '',
    image_source,
  }
  species.push(row)
  existingNames.add(row.scientific_name.toLowerCase())
  added.push(row)
  byGenus[row.genus] = (byGenus[row.genus] || 0) + 1
}

fs.writeFileSync(speciesPath, JSON.stringify(species, null, 2) + '\n')
console.log(`Added ${added.length} plants (catalog now ${species.length})`)
