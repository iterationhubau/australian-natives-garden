import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const speciesPath = path.join(__dirname, '../src/data/species.json')
const species = JSON.parse(fs.readFileSync(speciesPath, 'utf8'))

function plant(p) {
  return {
    pretreatment: p.pretreatment || 'None Required (cutting-grown / nursery stock common)',
    germination: p.germination || 'Cuttings preferred for cultivars. Species seed: sow on sandy native mix surface, keep lightly moist.',
    growth_rate: p.growth_rate || 'Moderate',
    conservation_status: p.conservation_status || (p.scientific_name.includes("'") ? 'Cultivar' : 'Least Concern'),
    conservation_locale: p.conservation_locale || (p.scientific_name.includes("'") ? 'Garden / nursery selection' : 'Australia'),
    conservation_description:
      p.conservation_description ||
      (p.scientific_name.includes("'")
        ? 'Garden cultivar / selection; not assessed as a wild conservation taxon.'
        : 'Secure in suitable native habitats; widely grown in Australian gardens.'),
    shade_tolerance: p.shade_tolerance || 'Full sun',
    water_requirement: p.water_requirement || 2,
    ...p,
  }
}

